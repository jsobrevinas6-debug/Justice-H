// Helper: Find closest Laguna municipality to given lat/lng using Haversine Formula
export function findNearestLagunaMunicipality(lat, lng) {
  if (!lat || !lng) return LAGUNA_MUNICIPALITIES[0];

  const userLat = parseFloat(lat);
  const userLng = parseFloat(lng);

  if (isNaN(userLat) || isNaN(userLng)) return LAGUNA_MUNICIPALITIES[0];

  const toRad = (value) => (value * Math.PI) / 180;
  const R = 6371; // Earth radius in km

  let nearest = LAGUNA_MUNICIPALITIES[0];
  let minDistance = Infinity;

  LAGUNA_MUNICIPALITIES.forEach((muni) => {
    const dLat = toRad(muni.lat - userLat);
    const dLng = toRad(muni.lng - userLng);
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(toRad(userLat)) *
        Math.cos(toRad(muni.lat)) *
        Math.sin(dLng / 2) *
        Math.sin(dLng / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const distance = R * c;

    if (distance < minDistance) {
      minDistance = distance;
      nearest = muni;
    }
  });

  return nearest;
}
